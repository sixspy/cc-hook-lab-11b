"""早卷 · test_schema_co_a.py —— 失败测甲：甲式正文被重排成新序，序红。

骨签：旧模式字段序不得被新模式重排。
本卷只验“字段顺序本身”：
  1. 甲式正文经组装后，字段序保持甲序，不被新序重排；
  2. 事件/投递详情里要列出“字段顺序”这一项本身；
  3. 声明的模式收成不可变快照：之后改声明为新式，旧投递的序不回刷。
"""
import os
import tempfile
from pathlib import Path

_tmp = tempfile.mkdtemp()
os.environ['数据目录'] = _tmp
os.environ['夹具目录'] = str(Path(__file__).resolve().parents[2] / 'fixtures')

from app import seed
from app.services import 夹具, 模式组装

# 两套并存模式的规范字段序（正文 key 序）
甲序 = ['事件号', '事件类型', '端点键', '载荷摘要', '优先级']
新序 = ['事件号', '优先级', '载荷摘要', '事件类型', '端点键']


def setup_module():
    seed.初始化库()


def _取甲式正文() -> dict:
    体 = 夹具.读取('模式复现/甲式正文')
    assert 体['模式'] == '甲式'
    return 体['事件'][0]


def test_甲式正文组装后字段序不被重排():
    正文 = _取甲式正文()
    声明 = 模式组装.声明模式('co-a-1', '甲式')
    投递 = 模式组装.组装('co-a-1', 正文)
    # 组装出的正文 key 序必须等于甲序
    assert list(投递['正文'].keys()) == 甲序, (
        f"序红：甲式正文被重排成 {list(投递['正文'].keys())}，应保持 {甲序}"
    )


def test_详情里列出字段顺序本身():
    正文 = _取甲式正文()
    模式组装.声明模式('co-a-2', '甲式')
    投递 = 模式组装.组装('co-a-2', 正文)
    详情 = 模式组装.投递详情(投递['投递号'])
    # 详情必须显式列出“字段顺序”这一项，且就是甲序本身
    assert '字段顺序' in 详情, '详情缺少“字段顺序”项'
    assert 详情['字段顺序'] == 甲序, (
        f"序红：详情字段顺序为 {详情['字段顺序']}，应为 {甲序}"
    )
    # 页面写甲式字段序也要保持甲序，不得按新序渲染
    assert 模式组装.页面字段序(投递['投递号']) == 甲序


def test_声明快照冻结_后改新式不回刷旧序():
    正文 = _取甲式正文()
    模式组装.声明模式('co-a-3', '甲式')
    投递 = 模式组装.组装('co-a-3', 正文)
    旧号 = 投递['投递号']
    # 之后把同一来源的声明改成新式：新模式只作用于新式正文，不得回刷旧投递
    模式组装.声明模式('co-a-3', '新式')
    详情 = 模式组装.投递详情(旧号)
    assert 详情['模式'] == '甲式', '快照被回刷：旧投递模式不应随声明改写'
    assert 详情['字段顺序'] == 甲序, '序红：旧投递字段序被新声明回刷'
